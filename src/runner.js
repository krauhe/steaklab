/* Deterministic event scheduler, shared by worker, browser fallback and tests. */
(() => {
'use strict';
function prepare(config,events,duration){
 const engine=new SteakPhysics.Engine(config),end=Math.min(2700,Math.max(180,+duration||720));
 const schedule=events.filter(e=>e.enabled!==false).map((e,index)=>({...e,time:Math.min(end,Math.max(0,+e.time||0)),index})).sort((a,b)=>a.time-b.time||a.index-b.index);
 return{engine,end,schedule,cursor:0,snapshots:[],warnings:[],next:0};
}
function makeSnapshot(engine){
 const s=engine.observe();if(s.panField)s.panField=Array.from(s.panField);
 return{s,T:Float32Array.from(engine.T),dA:Float32Array.from(engine.doses[0]),dB:Float32Array.from(engine.doses[1])};
}
function advance(job,until){
 while(job.engine.time<until-1e-8||job.snapshots.length===0){
  const e=job.engine;
  let acted=false;
  while(job.cursor<job.schedule.length&&job.schedule[job.cursor].time<=e.time+1e-8){const a=job.schedule[job.cursor++];acted=true;if(!e.action(a.type,a.value))job.warnings.push({time:e.time,type:a.type});}
  if(acted||e.time>=job.next-1e-8){job.snapshots.push(makeSnapshot(e));if(e.time>=job.next-1e-8)job.next=2*(Math.floor(e.time/2)+1);}
  const nextEvent=job.cursor<job.schedule.length?job.schedule[job.cursor].time:Infinity;
  const stop=Math.min(until,job.next,nextEvent);
  if(stop>e.time+1e-8)e.step(stop-e.time);else break;
 }
 if(job.engine.time>=job.end-1e-8){while(job.cursor<job.schedule.length&&job.schedule[job.cursor].time<=job.end+1e-8){const a=job.schedule[job.cursor++];if(!job.engine.action(a.type,a.value))job.warnings.push({time:job.end,type:a.type});}if(!job.snapshots.length||job.snapshots.at(-1).s.time<job.end-1e-8)job.snapshots.push(makeSnapshot(job.engine));}
 return job;
}
function finish(job){const m=job.engine.mesh;return{snapshots:job.snapshots,mesh:{nr:m.nr,nz:m.nz,R:m.R,H:m.H,nodes:m.nodes,triangles:m.triangles},panMesh:job.engine.panMesh?{R:job.engine.panMesh.R,outerRadius:job.engine.panMesh.outerRadius,wallHeight:job.engine.panMesh.wallHeight,bottomCount:job.engine.panMesh.bottomCount,wallCount:job.engine.panMesh.wallCount,nodes:job.engine.panMesh.nodes}:null,warnings:job.warnings,config:job.engine.config,duration:job.end};}
function run(config,events,duration){const job=prepare(config,events,duration);advance(job,job.end);return finish(job);}
// A suggestion is generated by solving the same model, including a prospective
// rest. It is not a fitted cooking-time table or a food-safety certificate.
function* suggestSteps(config,target){
 const e=new SteakPhysics.Engine(config),c=e.config,minced=c.meat==='minced',goal=minced?75:Math.min(85,Math.max(45,Number(target)||56));
 const events=[],record=(type,value)=>{events.push({time:e.time,type,value});e.action(type,value);};
 const preheat={beef:200,minced:175,pork:185,chicken:175,fish:165}[c.meat];record('power',12);
 while(e.panContactTemp<preheat&&e.time<360)e.step(1);
 record('oil',10);e.step(2);record('add');const placed=e.time;record('power',c.meat==='beef'?5:4);
 const restSeconds=Math.round(Math.min(180,Math.max(60,c.thickness*(c.meat==='fish'?2.4:4.8)))/5)*5;
 const guideline=c.meat==='chicken'||minced?75:63;
 let flipAt=placed+60,reduced=false,predicted=null,reached=false;
 function forecast(){const copy=e.clone();copy.action('rest');copy.action('power',0);let peak=copy.observe().core;for(let t=0;t<restSeconds;t+=5){copy.step(Math.min(5,restSeconds-t));peak=Math.max(peak,copy.observe().core);}return{peak,afterRest:copy.observe().core,atRemoval:e.observe().core,minAtRemoval:e.observe().min};}
 const lastRemoval=2700-restSeconds;
 while(e.time<lastRemoval-1e-8){
  if(!reduced&&e.time>=placed+60-1e-8){record('power',c.meat==='beef'||c.meat==='pork'?3:2);reduced=true;}
  if(e.time>=flipAt-1e-8){record('flip');flipAt+=60;}
  const s=e.observe();
  // Minced-patty suggestions require the current whole modeled field to reach
  // 75 °C on the pan. A forecast rest peak cannot satisfy this condition.
  // This planner rule does not restrict manually scheduled timeline actions.
  if(minced&&s.min>=goal){reached=true;break;}
  if(!minced&&s.core>goal-28){
   predicted=forecast();if(predicted.peak>=goal){reached=true;break;}
  }
  e.step(Math.min(5,flipAt-e.time,!reduced?placed+60-e.time:Infinity,lastRemoval-e.time));
  yield e.time;
 }
 if(minced)reached=e.observe().min>=goal;
 if(!predicted||!reached)predicted=forecast();
 record('rest');record('power',0);const removed=e.time;
 return{events,duration:Math.min(2700,Math.max(180,removed+restSeconds)),target:goal,preheat,placed,removed,restSeconds,predicted,reached,guideline};
}
function suggest(config,target){const it=suggestSteps(config,target);let step;do{step=it.next();}while(!step.done);return step.value;}
async function suggestAsync(config,target,cancelled=()=>false){const it=suggestSteps(config,target);let step;do{if(cancelled())return null;for(let i=0;i<5;i++){step=it.next();if(step.done)return step.value;}await new Promise(resolve=>setTimeout(resolve,0));}while(!step.done);return step.value;}
globalThis.SteakRunner={prepare,advance,finish,run,suggest,suggestAsync};
})();
